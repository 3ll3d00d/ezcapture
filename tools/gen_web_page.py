"""Embeds common/web/index.html in common/web_page.h as a gzipped byte array.

    python tools/gen_web_page.py          regenerate the header
    python tools/gen_web_page.py --check  exit 1 if the header does not match index.html (used by CI)

The check compares the SHA-256 of index.html recorded in the header, not the gzip bytes, so it does not depend on
the zlib version.
"""
import gzip
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'common' / 'web' / 'index.html'
DST = ROOT / 'common' / 'web_page.h'


def main():
    # hash and compress the text with LF line endings so a CRLF checkout gives the same result
    html = SRC.read_bytes().replace(b'\r\n', b'\n')
    digest = hashlib.sha256(html).hexdigest()

    if '--check' in sys.argv:
        current = DST.read_text(encoding='utf-8') if DST.exists() else ''
        m = re.search(r'sha256\{"([0-9a-f]{64})"\}', current)
        if not m or m.group(1) != digest:
            print(f'{DST.relative_to(ROOT)} is stale, run python tools/gen_web_page.py', file=sys.stderr)
            return 1
        return 0

    data = gzip.compress(html, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 24):
        lines.append('\t\t' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    body = '\n'.join(lines)
    DST.write_text(f'''// Generated by tools/gen_web_page.py from common/web/index.html, do not edit.
#ifndef WEB_PAGE_HEADER
#define WEB_PAGE_HEADER

#include <string_view>

namespace web_page
{{
	// of index.html with LF line endings, checked by gen_web_page.py --check
	inline constexpr std::string_view sha256{{"{digest}"}};

	// {len(html)} bytes of html
	inline constexpr unsigned char gzipped[] = {{
{body}
	}};
}}

#endif
''', encoding='utf-8', newline='\n')
    print(f'{len(html)} bytes -> {len(data)} gzipped')
    return 0


if __name__ == '__main__':
    sys.exit(main())
